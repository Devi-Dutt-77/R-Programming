# Program to demonstrate simple functions in R


# Create a simple function
greet <- function() {
  print("Hello! Welcome to R Programming")
}

# Call the function
greet()


# Create a function to display a message
welcome_message <- function() {
  print("Learning Statistical Analysis using R")
}

# Call the function
welcome_message()


# Create a simple function to display a number
display_number <- function() {
  number <- 100
  print(paste("The number is:", number))
}

# Call the function
display_number()


